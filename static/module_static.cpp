// static/module_static.cpp -- static-link replacement for winrt/dll/module.cpp.
//
// What: Win2D's winrt/lib/winrt.lib.uap.vcxproj already produces a static library (winrt.lib)
// that contains all of Win2D. The DLL project (winrt/dll) only adds module.cpp, which supplies
// DllMain, DllGetActivationFactory, DllGetClassObject and DllCanUnloadNow, plus a .def and .rc.
// This file replaces module.cpp so that winrt.lib can be linked straight into a host exe (for
// example a .NET NativeAOT app) instead of shipping Microsoft.Graphics.Canvas.dll.
//
// Why it differs from module.cpp:
//  * There is no DllMain (the host is an exe). The ETW provider and TraceLogging registration
//    that DllMain did on DLL_PROCESS_ATTACH happen on the first activation instead, guarded by
//    std::call_once. The matching unregistration on DLL_PROCESS_DETACH is skipped; the process
//    is exiting at that point anyway.
//  * The entry points are exported under unique names (Win2DStatic_*) so they cannot collide
//    with a DllGetActivationFactory/DllGetClassObject defined elsewhere in the host exe.
//    The host routes activation of Microsoft.Graphics.Canvas.* classes to
//    Win2DStatic_DllGetActivationFactory (see static/README.md for the CsWinRT hook).
//
// Built by static/build-static.ps1 into win2dmod.lib with /MT (hybrid CRT, matching winrt.lib).

#include <windows.h>
#include <wrl/module.h>
#include <mutex>

#pragma warning(push)
#pragma warning(disable:4459)
#include <win2d.etw.h>      // generated by the winrt.lib build (mc.exe) into obj\etw\<platform>\Release
#pragma warning(pop)

extern void RegisterTraceLogging();

static std::once_flag g_win2dInit;

static void EnsureWin2DInitialized()
{
    std::call_once(g_win2dInit, []
    {
        EventRegisterWin2D();
        RegisterTraceLogging();
    });
}

extern "C" HRESULT __stdcall Win2DStatic_DllGetActivationFactory(
    HSTRING activatableClassId,
    IActivationFactory** factory)
{
    EnsureWin2DInitialized();
    auto& module = ::Microsoft::WRL::Module< ::Microsoft::WRL::InProc >::GetModule();
    return module.GetActivationFactory(activatableClassId, factory);
}

extern "C" HRESULT __stdcall Win2DStatic_DllGetClassObject(REFCLSID clsid, REFIID iid, void** obj)
{
    EnsureWin2DInitialized();
    auto& module = ::Microsoft::WRL::Module< ::Microsoft::WRL::InProc >::GetModule();
    return module.GetClassObject(clsid, iid, obj);
}
